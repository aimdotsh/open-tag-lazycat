import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lockfiles = [
  ["server/runtime", "package-lock.json"],
  ["web", "web/package-lock.json"],
  ["documentation build", "docs-site/package-lock.json"],
];

function declaredLicense(baseDir, packagePath, packageName, lockEntry) {
  if (typeof lockEntry.license === "string" && lockEntry.license.trim()) {
    return lockEntry.license.trim();
  }
  try {
    const packageJson = JSON.parse(
      readFileSync(path.join(baseDir, packagePath, "package.json"), "utf8"),
    );
    if (typeof packageJson.license === "string" && packageJson.license.trim()) {
      return packageJson.license.trim();
    }
    if (Array.isArray(packageJson.licenses)) {
      const values = packageJson.licenses
        .map((item) => typeof item === "string" ? item : item?.type)
        .filter(Boolean);
      if (values.length) return values.join(" OR ");
    }
  } catch {
    // A lockfile remains authoritative for version pinning even when optional
    // platform packages are not installed on the build host.
  }
  // satteri 0.9.3 and its platform packages omit the package.json license
  // field, but the source package distributes an MIT LICENSE file.
  if (packageName === "satteri" || packageName.startsWith("@bruits/satteri-")) {
    return "MIT (declared in satteri LICENSE)";
  }
  return "UNKNOWN — inspect package license before redistribution";
}

const rows = [];
for (const [group, relativeLockfile] of lockfiles) {
  const absoluteLockfile = path.join(root, relativeLockfile);
  const baseDir = path.dirname(absoluteLockfile);
  const lock = JSON.parse(readFileSync(absoluteLockfile, "utf8"));
  for (const [packagePath, entry] of Object.entries(lock.packages ?? {})) {
    if (!packagePath || !packagePath.includes("node_modules/")) continue;
    const name = entry.name
      ?? packagePath.slice(packagePath.lastIndexOf("node_modules/") + "node_modules/".length);
    rows.push({
      group,
      name,
      version: entry.version ?? "UNKNOWN",
      license: declaredLicense(baseDir, packagePath, name, entry),
    });
  }
}

rows.sort((a, b) =>
  a.group.localeCompare(b.group)
  || a.name.localeCompare(b.name)
  || a.version.localeCompare(b.version)
);

const lines = [
  "# Locked third-party package inventory",
  "",
  "<!-- Generated by scripts/generate-third-party-notices.mjs. Do not edit manually. -->",
  "",
  "This inventory records package metadata from the npm lockfiles used to build",
  "the community-maintained LazyCat distribution. The license files shipped by",
  "the packages are authoritative.",
  "",
  "| Group | Package | Locked version | Declared license |",
  "| --- | --- | --- | --- |",
  ...rows.map(({ group, name, version, license }) =>
    `| ${group} | \`${name}\` | \`${version}\` | ${license.replaceAll("|", "\\|")} |`
  ),
];

const output = path.join(root, "docs/third-party-packages.md");
writeFileSync(output, `${lines.join("\n")}\n`);
console.log(`wrote ${path.relative(root, output)} (${rows.length} packages)`);
